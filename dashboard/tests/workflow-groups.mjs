import assert from 'node:assert/strict'
import { normalizeWorkflow, createGraphAction, insertGraphNode, connectGraph, copyGraphNode, getGraphTriggers, buildWorkflowGraph, removeGraphNode, graphExecutionActions, groupGraphNodes, moveGraphNodes, switchGroupType, visibleBranches, insertionParent, createRecoveryGroup, findRecoveryGroup } from '../src/lib/workflowGraph.js'
import { collectTriggerLeaves, buildTestInputFields, actionOutputDefs } from '../src/lib/bindings.js'
import { trigger, action, eventGroup, wire, ruleWith, reference, schema, presentation } from './canvas-fixtures.mjs'

const a = trigger('alpha001'), b = trigger('beta0001'), measure = action('measure01', 'measure'), after = action('after0001')
const rule = ruleWith([a, b, measure, after], [wire(a, measure, 'control', 'event'), wire(measure, after)])
assert.equal(normalizeWorkflow(rule), rule.workflow)
for (const key of ['condition', 'event', 'trigger', 'actions', 'preconditions']) assert.throws(() => normalizeWorkflow({ ...rule, [key]: [] }), /旧条件模型/)
for (const key of ['activation', 'condition_graph', 'workflow', 'then', 'elif', 'else', 'triggers']) assert.throws(() => normalizeWorkflow(ruleWith([{ ...eventGroup('old'), [key]: {} }])), /旧条件模型/)
assert.deepEqual(getGraphTriggers(rule), [a.trigger, b.trigger])
assert.deepEqual(collectTriggerLeaves(rule), [a.trigger, b.trigger])
const group = groupGraphNodes(rule.workflow, [a.binding_id, b.binding_id], 'if')
assert.equal(a.parent, group.binding_id)
assert.equal(b.parent, group.binding_id)
assert.equal(rule.workflow.edges.length, 1)
assert.deepEqual(rule.workflow.edges[0], wire(measure, after))
assert(!rule.workflow.edges.some(edge => edge.source === group.binding_id || edge.target === group.binding_id))
assert.equal(connectGraph(rule.workflow, a.binding_id, 'event', group.binding_id, group.branches[0].id), '')
const onceConnected = JSON.stringify(rule.workflow)
assert.equal(connectGraph(rule.workflow, a.binding_id, 'event', group.binding_id, group.branches[0].id), '', '已有条件连接重复拖入保持不变')
assert.equal(JSON.stringify(rule.workflow), onceConnected)
assert.equal(connectGraph(rule.workflow, b.binding_id, 'event', group.binding_id, group.branches[1].id), '')
assert.equal(group.branches.length, 4)
assert.equal(group.branches.at(-1).else, true)
assert.deepEqual(visibleBranches(rule.workflow, group, false).map(branch => branch.id), group.branches.slice(0, 2).map(branch => branch.id))
assert.equal(visibleBranches(rule.workflow, group, true).length, 4)
const beforeInvalid = JSON.stringify(rule)
assert.match(connectGraph(rule.workflow, b.binding_id, 'event', group.binding_id, group.branches[0].id), /只接一个/)
assert.match(connectGraph(rule.workflow, b.binding_id, 'event', group.binding_id, group.branches.at(-1).id), /ELSE/)
assert.equal(JSON.stringify(rule), beforeInvalid)
const nested = groupGraphNodes(rule.workflow, [a.binding_id, b.binding_id], 'all')
assert.equal(nested.parent, group.binding_id)
assert.equal(rule.workflow.edges.length, 1)
assert.equal(connectGraph(rule.workflow, a.binding_id, 'event', nested.binding_id), '')
assert.equal(connectGraph(rule.workflow, b.binding_id, 'event', nested.binding_id), '')
assert.equal(connectGraph(rule.workflow, nested.binding_id, 'result', group.binding_id, group.branches[0].id), '')
assert.match(connectGraph(rule.workflow, group.binding_id, group.branches[0].id, nested.binding_id, 'input', 'condition'), /循环/)
const snapshot = JSON.stringify(rule)
for (const expanded of [new Set(), new Set([group.binding_id]), new Set([group.binding_id, nested.binding_id])]) {
  const drawn = buildWorkflowGraph(rule, expanded, schema, presentation)
  assert.equal(new Set(drawn.nodes.map(node => node.id)).size, drawn.nodes.length)
  const ids = new Set(drawn.nodes.map(node => node.id))
  assert(drawn.edges.every(edge => ids.has(edge.from) && ids.has(edge.to)), JSON.stringify({ expanded: [...expanded], missing: drawn.edges.filter(edge => !ids.has(edge.from) || !ids.has(edge.to)) }))
}
assert.equal(JSON.stringify(rule), snapshot)
assert.equal(moveGraphNodes(rule.workflow, [nested.binding_id], nested.binding_id), '不能把组拖入自身或其内部组')
assert.equal(moveGraphNodes(rule.workflow, [a.binding_id], null), '')
assert(!a.parent)
assert(!rule.workflow.edges.some(edge => edge.source === a.binding_id || edge.target === a.binding_id))
assert(rule.workflow.edges.some(edge => edge.source === b.binding_id && edge.target === nested.binding_id))
switchGroupType(rule.workflow, group, 'any')
assert.equal(group.group_type, 'any')
assert.deepEqual(group.branches, [])
assert(!rule.workflow.edges.some(edge => edge.source === group.binding_id || edge.target === group.binding_id))
assert(rule.workflow.nodes.includes(a) && rule.workflow.nodes.includes(b))
const copied = copyGraphNode(nested, rule.workflow)
assert.notEqual(copied.binding_id, nested.binding_id)
assert.equal(copied._copyNodes.length, 1)
assert.notEqual(copied._copyNodes[0].trigger.binding_id, b.trigger.binding_id)
assert.equal(copied._copyNodes[0].parent, copied.binding_id)
assert.equal(copied._copyEdges[0].target, copied.binding_id)
const assignment = createGraphAction('set_variable')
insertGraphNode(rule.workflow, assignment, measure.binding_id)
assert.equal(rule.workflow.edges.find(edge => edge.source === measure.binding_id).target, assignment.binding_id)
assert.equal(rule.workflow.edges.find(edge => edge.source === assignment.binding_id).target, after.binding_id)
removeGraphNode(rule.workflow, nested)
assert(!rule.workflow.nodes.includes(b))
assert(!rule.workflow.edges.some(edge => edge.source === b.binding_id || edge.target === b.binding_id))
const upstream = action('upstream01', 'measure'), selected = action('selected01', 'log', { text: reference('step', upstream.binding_id, ['latency']) })
const partial = ruleWith([upstream, selected], [wire(upstream, selected)])
assert(buildTestInputFields(partial, schema, { startStepId: selected.binding_id }).some(field => field.scope === 'step' && field.node === upstream.binding_id))
assert.deepEqual(graphExecutionActions(partial, { startStepId: selected.binding_id }).map(node => node.binding_id), [selected.binding_id])
const exported = createGraphAction('action_group')
upstream.parent = exported.binding_id
exported.exports = { speed: reference('step', upstream.binding_id, ['latency']), token: { $ref: { scope: 'variable', node: 'v_secret001', path: [], on_missing: 'skip' } } }
const outputs = actionOutputDefs(exported, schema, ruleWith([exported, upstream], [], { variables: [{ id: 'v_secret001', name: '密码', sensitive: true, value_type: 'text' }] }))
assert.equal(outputs.find(output => output.name === 'speed').value_type.type, 'number')
assert.equal(outputs.find(output => output.name === 'token').sensitive, true)
assert.equal(outputs.find(output => output.name === 'token').required, false)


const referenceOwner = action('referenceowner', 'log', { text: reference('trigger', 't_cross001', ['state']) })
const crossingTrigger = trigger('cross001'), crossingGroup = eventGroup('crossgroup', 'all')
const preservedLiteral = { $literal: reference('trigger', crossingTrigger.trigger.binding_id, ['state']) }
referenceOwner.params.literal = preservedLiteral
const crossingRule = ruleWith([crossingTrigger, crossingGroup, referenceOwner], [wire(crossingTrigger, referenceOwner, 'control', 'event')])
assert.equal(moveGraphNodes(crossingRule.workflow, [crossingTrigger.binding_id], crossingGroup.binding_id), '')
assert.equal(referenceOwner.params.text, '')
assert.deepEqual(referenceOwner.params.literal, preservedLiteral)
assert.equal(crossingRule.workflow.edges.length, 0)
const firstFailure = action('failurefirst', 'measure'), secondFailure = action('failuresecond', 'log', { text: reference('step', firstFailure.binding_id, ['latency']) })
const failureOwner = action('failureowner', 'log')
const recoveryGraph = { nodes: [failureOwner, firstFailure, secondFailure], edges: [] }
const recoveryGroup = createRecoveryGroup(recoveryGraph, failureOwner)
firstFailure.parent = recoveryGroup.binding_id; secondFailure.parent = recoveryGroup.binding_id
assert.equal(connectGraph(recoveryGraph, recoveryGroup.binding_id, 'entry', firstFailure.binding_id), '')
assert.equal(connectGraph(recoveryGraph, firstFailure.binding_id, 'next', secondFailure.binding_id), '')
assert.equal(findRecoveryGroup(recoveryGraph, failureOwner), recoveryGroup)
assert.match(connectGraph(recoveryGraph, recoveryGroup.binding_id, 'next', failureOwner.binding_id), /外部后继/)
const failureCopy = copyGraphNode(failureOwner, recoveryGraph)
const copiedFirst = failureCopy._copyNodes.find(node => node.type === 'measure')
const copiedSecond = failureCopy._copyNodes.find(node => node.type === 'log')
assert.notEqual(copiedFirst.binding_id, firstFailure.binding_id)
assert.equal(copiedSecond.params.text.$ref.node, copiedFirst.binding_id)
assert(failureCopy._copyEdges.some(edge => edge.source === failureCopy.binding_id && edge.port === 'failure'))
assert.throws(() => normalizeWorkflow(ruleWith([{ ...failureOwner, failure_actions: [] }])), /旧条件模型/)

const insertionTrigger = trigger('inserttrigger'), insertionTarget = eventGroup('inserttarget')

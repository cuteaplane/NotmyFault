const insertionRule = ruleWith([insertionTrigger, insertionTarget], [conditionWire])
const insertedAnd = eventGroup('insertand', 'all')
insertGraphNode(insertionRule.workflow, insertedAnd, conditionWire.source, conditionWire.port, conditionWire)
assert.equal(insertionRule.workflow.edges.length, 2)
assert.equal(insertionRule.workflow.edges[0].target, insertedAnd.binding_id)
assert.equal(insertionRule.workflow.edges[0].target_port, 'input')
assert.equal(insertionRule.workflow.edges[1].source, insertedAnd.binding_id)
assert.equal(insertionRule.workflow.edges[1].port, 'result')
assert.equal(insertionRule.workflow.edges[1].target_port, insertionTarget.branches[0].id)
assert(insertionRule.workflow.edges.every(edge => edge.channel === 'condition'))
const chainedTrigger = trigger('chaintrigger'), chainedAction = action('chainaction')
const chainedRule = ruleWith([chainedTrigger, chainedAction], [wire(chainedTrigger, chainedAction, 'control', 'event')])
const chainedAnd = eventGroup('chainand', 'all')
insertGraphNode(chainedRule.workflow, chainedAnd, chainedTrigger.binding_id, 'event')
assert.equal(chainedRule.workflow.edges.find(edge => edge.source === chainedTrigger.binding_id).target, chainedAnd.binding_id)
assert.equal(chainedRule.workflow.edges.find(edge => edge.source === chainedAnd.binding_id).port, 'result')
assert.equal(chainedRule.workflow.edges.find(edge => edge.source === chainedAnd.binding_id).target, chainedAction.binding_id)
